def build_analyst_messages(payload: dict[str, Any]) -> list[dict[str, str]]:
    """Build provider-grounded messages for an LLM analyst.

    The LLM is an analysis layer, not the source of truth. Hard signal gates must
    still be enforced deterministically by the runtime after model output.
    """
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": json.dumps(payload, ensure_ascii=False, separators=(",", ":"))},
    ]
